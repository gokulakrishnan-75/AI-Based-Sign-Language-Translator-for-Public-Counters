export function translateSign(signName, langCode = 'en') {
  if (!signName) return null;
  const entry = MULTILINGUAL_TRANSLATIONS[signName];
  if (!entry) return { text: signName, spoken: signName };
  return entry[langCode] || entry['en'] || { text: signName, spoken: signName };
}

export function translateSentence(tokens, langCode = 'en') {
  if (!tokens || tokens.length === 0) return { text: "", spoken: "" };
  const translatedWords = tokens.map(t => {
    const tr = translateSign(t, langCode);
    return tr ? tr.text : t;
  });
  const spokenPhrases = tokens.map(t => {
    const tr = translateSign(t, langCode);
    const phrase = tr ? tr.spoken : t;
    return (phrase || '').trim();
  }).filter(Boolean);

  const formattedSpoken = spokenPhrases.map(p => {
    if (/[.!?।]$/.test(p)) return p;
    return p + '.';
  }).join(' ');

  return {
    text: translatedWords.join(' '),
    spoken: formattedSpoken
  };
}
